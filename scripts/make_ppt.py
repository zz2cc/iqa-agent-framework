# ══════ Markdown 文案 ══════
def emit_md():
    L = ["# 验收汇报 PPT 文案（5 分钟）", "",
         "> 总时长约 5 分 05 秒（含备用页）。每页含：要点、配图位置、逐字稿。", ""]
    for i, (title, bullets, fig, notes, t) in enumerate(SLIDES, 1):
        L += [f"## 第 {i} 页｜{title.split(chr(10))[0]}（{t}）", ""]
        L += [f"- {b}" for b in bullets]
        if fig: L += ["", f"【配图】docs/figs/{fig}"]
        L += ["", f"**逐字稿：** {notes}", ""]
    path = os.path.join(ROOT, "docs", "汇报PPT文案.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("md ->", path)

# ══════ PPTX ══════
def emit_pptx():
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    blank = prs.slide_layouts[6]

    for i, (title, bullets, fig, notes, t) in enumerate(SLIDES, 1):
        s = prs.slides.add_slide(blank)
        # 标题
        tb = s.shapes.add_textbox(Inches(0.6), Inches(0.35), Inches(12.1), Inches(1.2))
        tf = tb.text_frame; tf.word_wrap = True
        for k, line in enumerate(title.split("\n")):
            p = tf.paragraphs[0] if k == 0 else tf.add_paragraph()
            r = p.add_run(); r.text = line
            r.font.size = Pt(30 if i > 1 else 34); r.font.bold = True
            r.font.color.rgb = RGBColor(0, 0, 0)
        # 时间标签
        tb2 = s.shapes.add_textbox(Inches(11.3), Inches(0.15), Inches(1.8), Inches(0.4))
        r = tb2.text_frame.paragraphs[0].add_run(); r.text = f"[{t}]"
        r.font.size = Pt(12); r.font.color.rgb = RGBColor(0x88, 0x88, 0x88)
        # 要点
        has_fig = fig is not None
        w = Inches(6.7) if has_fig else Inches(12.1)
        tb3 = s.shapes.add_textbox(Inches(0.6), Inches(1.75), w, Inches(5.2))
        tf = tb3.text_frame; tf.word_wrap = True
        for k, b in enumerate(bullets):
            p = tf.paragraphs[0] if k == 0 else tf.add_paragraph()
            p.space_after = Pt(10)
            r = p.add_run(); r.text = ("• " if i > 1 else "") + b
            r.font.size = Pt(16 if i > 1 else 20)
            r.font.color.rgb = RGBColor(0, 0, 0)
            if i == 1: p.alignment = PP_ALIGN.CENTER
        # 配图
        if has_fig:
            s.shapes.add_picture(os.path.join(FIGS, fig), Inches(7.5), Inches(1.9), width=Inches(5.4))
        # 逐字稿 → 备注
        s.notes_slide.notes_text_frame.text = f"[{t}] {notes}"

    path = os.path.join(ROOT, "docs", "汇报.pptx")
    prs.save(path)
    print("pptx ->", path)

if __name__ == "__main__":
    emit_md()
    emit_pptx()
